import {
  BadRequestException,
  ConflictException,
  Injectable,
  NotFoundException,
} from '@nestjs/common';
import { InjectRepository } from '@nestjs/typeorm';
import { randomUUID } from 'node:crypto';
import { EntityManager, Repository } from 'typeorm';
import type { QueryDeepPartialEntity } from 'typeorm/query-builder/QueryPartialEntity';
import { CompaniesService } from '../companies/companies.service';
import { AuditEvent, Company, Document, TerminPlan, TerminPlanItem } from '../database/entities';
import { DocumentType } from '../database/entities/enums';
import { Decimal } from '../database/decimal.transformer';
import { activeInvoiceOf } from '../documents/document-links';
import { DocumentsService } from '../documents/documents.service';
import { InvoiceConversionService } from '../documents/invoice-conversion.service';
import { activeGoodsReceipt } from '../goods-receipts/goods-receipt-links';
import { GoodsReceiptsService } from '../goods-receipts/goods-receipts.service';
import type { TerminAssignment } from './termin-assignment';
import {
  GoodsReceiptTerminPlanDto,
  InvoiceTerminPlanDto,
  QuotationTerminPlanDto,
  type TerminGenerateOption,
  UpdateTerminPlanDto,
} from './dto/termin-plan.dto';
import { formatPercentage, terminBounds, validatePercentages } from './termin-math';
import { terminInvoicePayload } from './termin-invoice';
import {
  type InvoicePlanBase,
  isLive,
  loadTerminPlanView,
  planDocuments,
  planItems,
  planOfSource,
  type TerminPlanView,
} from './termin-views';

export interface TerminPlanResult {
  plan: TerminPlanView;
  /** Documents generated by this request, in termin order. */
  documents: Array<{ id: string; sequence: number }>;
}

/**
 * Payment termins: splitting an accepted quotation into goods receipts, or a goods receipt or
 * a typed invoice into invoices, by percentage. Plans are created with their first (or every)
 * termin generated; the rest are generated later, one by one or together. A termin whose
 * document is cancelled, voided or deleted can be generated again. Percentages of termins
 * without a live document can be changed; a plan without live documents can be deleted.
 */
@Injectable()
export class TerminsService {
  constructor(
    @InjectRepository(TerminPlan) private readonly plans: Repository<TerminPlan>,
    private readonly companies: CompaniesService,
    private readonly receipts: GoodsReceiptsService,
    private readonly conversions: InvoiceConversionService,
    private readonly invoices: DocumentsService,
  ) {}

  /** Accepted quotation → goods receipts in termins. */
  async createForQuotation(
    workspaceId: string,
    userId: string,
    dto: QuotationTerminPlanDto,
  ): Promise<TerminPlanResult> {
    this.requireValidSplit(dto.percentages);

    return this.inTransaction(async (manager) => {
      const quotation = await this.receipts.lockAcceptedQuotation(
        manager,
        workspaceId,
        dto.quotationId,
      );

      const receipt = await activeGoodsReceipt(manager, quotation.id);
      if (receipt) {
        throw new ConflictException(
          `Quotation ${quotation.documentNumber} already has goods receipt ${receipt.number}. Cancel or delete it to receive the quotation in termins.`,
        );
      }
      if (await planOfSource(manager, quotation.id, DocumentType.GOODS_RECEIPT)) {
        throw new ConflictException(
          `Quotation ${quotation.documentNumber} already has a termin plan.`,
        );
      }

      const plan = await this.savePlan(manager, {
        workspaceId,
        companyId: quotation.companyId,
        documentType: DocumentType.GOODS_RECEIPT,
        sourceDocumentId: quotation.id,
        basePayload: null,
        createdById: userId,
        percentages: dto.percentages,
      });
      await this.recordPlanEvent(manager, workspaceId, userId, plan, 'created', {
        targetType: 'quotation',
        targetId: quotation.id,
        number: quotation.documentNumber,
        percentages: dto.percentages,
      });

      return this.generateIn(manager, workspaceId, userId, plan, dto.percentages, dto.generate);
    });
  }

  /** Received goods receipt → invoices in termins. */
  async createForGoodsReceipt(
    workspaceId: string,
    userId: string,
    dto: GoodsReceiptTerminPlanDto,
  ): Promise<TerminPlanResult> {
    this.requireValidSplit(dto.percentages);

    return this.inTransaction(async (manager) => {
      const receipt = await this.conversions.lockReceivedReceipt(
        manager,
        workspaceId,
        dto.goodsReceiptId,
      );

      if (receipt.terminSequence !== null) {
        throw new ConflictException(
          `Goods receipt ${receipt.documentNumber} is itself termin ${receipt.terminSequence} of its quotation, so it is invoiced in one invoice.`,
        );
      }
      const invoice = await activeInvoiceOf(manager, receipt.id);
      if (invoice) {
        throw new ConflictException(
          `Goods receipt ${receipt.documentNumber} already has invoice ${invoice.number}. Void or delete it to bill the receipt in termins.`,
        );
      }
      if (await planOfSource(manager, receipt.id, DocumentType.INVOICE)) {
        throw new ConflictException(
          `Goods receipt ${receipt.documentNumber} already has a termin plan.`,
        );
      }

      const plan = await this.savePlan(manager, {
        workspaceId,
        companyId: receipt.companyId,
        documentType: DocumentType.INVOICE,
        sourceDocumentId: receipt.id,
        basePayload: null,
        createdById: userId,
        percentages: dto.percentages,
      });
      await this.recordPlanEvent(manager, workspaceId, userId, plan, 'created', {
        targetType: 'goods_receipt',
        targetId: receipt.id,
        number: receipt.documentNumber,
        percentages: dto.percentages,
      });

      return this.generateIn(manager, workspaceId, userId, plan, dto.percentages, dto.generate);
    });
  }

  /** An invoice typed in the generator → invoices in termins. */
  async createForInvoice(
    workspaceId: string,
    userId: string,
    dto: InvoiceTerminPlanDto,
  ): Promise<TerminPlanResult> {
    this.requireValidSplit(dto.percentages);
    const company = await this.companies.resolveCompany(workspaceId, dto.invoice.companyId);
    const base: InvoicePlanBase = {
      invoice: {
        ...dto.invoice,
        companyId: company.id,
        taxMode: dto.invoice.taxMode ?? company.defaultTaxMode,
      },
      currency: company.defaultCurrency,
    };

    return this.inTransaction(async (manager) => {
      const plan = await this.savePlan(manager, {
        workspaceId,
        companyId: company.id,
        documentType: DocumentType.INVOICE,
        sourceDocumentId: null,
        basePayload: base as unknown as Record<string, unknown>,
        createdById: userId,
        percentages: dto.percentages,
      });
      const result = await this.generateIn(
        manager,
        workspaceId,
        userId,
        plan,
        dto.percentages,
        dto.generate,
        company,
      );
      await this.recordPlanEvent(manager, workspaceId, userId, plan, 'created', {
        targetType: 'invoice',
        targetId: result.documents[0]?.id ?? plan.id,
        number: null,
        percentages: dto.percentages,
      });
      return result;
    });
  }

  async get(workspaceId: string, planId: string): Promise<TerminPlanView> {
    const plan = await this.plans.findOne({ where: { id: planId, workspaceId } });
    if (!plan) {
      throw new NotFoundException('Termin plan not found.');
    }
    return loadTerminPlanView(this.plans.manager, plan);
  }

  /**
   * New percentages (and count). Termins with a live document keep their percentage, and
   * termins can only be removed from the end when they have no live document.
   */
  async update(
    workspaceId: string,
    userId: string,
    planId: string,
    dto: UpdateTerminPlanDto,
  ): Promise<TerminPlanView> {
    this.requireValidSplit(dto.percentages);

    await this.inTransaction(async (manager) => {
      const plan = await this.lockPlan(manager, workspaceId, planId);
      const [items, documents] = await Promise.all([
        planItems(manager, plan.id),
        planDocuments(manager, plan.id),
      ]);
      const live = new Set(
        documents.filter((row) => isLive(row.status)).map((row) => Number(row.sequence)),
      );

      for (const item of items) {
        if (!live.has(item.sequence)) continue;
        const next = dto.percentages[item.sequence - 1];
        if (next === undefined) {
          throw new ConflictException(
            `Termin ${item.sequence} has a live document, so it cannot be removed. Cancel, void or delete it first.`,
          );
        }
        if (!item.percentage.eq(next)) {
          throw new ConflictException(
            `Termin ${item.sequence} already has a live document at ${formatPercentage(item.percentage.toNumber())}; its percentage cannot change.`,
          );
        }
      }

      await manager.getRepository(TerminPlanItem).delete({ planId: plan.id });
      await this.saveItems(manager, plan.id, dto.percentages);
      await manager.getRepository(TerminPlan).update({ id: plan.id }, { updatedAt: new Date() });
      await this.recordPlanEvent(manager, workspaceId, userId, plan, 'updated', {
        ...(await this.eventTarget(manager, plan)),
        percentages: dto.percentages,
      });
    });

    return this.get(workspaceId, planId);
  }

  async generate(
    workspaceId: string,
    userId: string,
    planId: string,
    sequence: number,
  ): Promise<TerminPlanResult> {
    return this.inTransaction(async (manager) => {
      const plan = await this.lockPlan(manager, workspaceId, planId);
      const items = await planItems(manager, plan.id);
      if (!items.some((item) => item.sequence === sequence)) {
        throw new NotFoundException(`This plan has no termin ${sequence}.`);
      }
      return this.generateSequences(manager, workspaceId, userId, plan, items, [sequence]);
    });
  }

  /** Every termin that has no live document and a share above 0%. */
  async generateRemaining(
    workspaceId: string,
    userId: string,
    planId: string,
  ): Promise<TerminPlanResult> {
    return this.inTransaction(async (manager) => {
      const plan = await this.lockPlan(manager, workspaceId, planId);
      const [items, documents] = await Promise.all([
        planItems(manager, plan.id),
        planDocuments(manager, plan.id),
      ]);
      const live = new Set(
        documents.filter((row) => isLive(row.status)).map((row) => Number(row.sequence)),
      );
      const sequences = items
        .filter((item) => !live.has(item.sequence) && item.percentage.gt(0))
        .map((item) => item.sequence);

      if (sequences.length === 0) {
        throw new ConflictException('Every termin with a percentage already has a document.');
      }
      return this.generateSequences(manager, workspaceId, userId, plan, items, sequences);
    });
  }

  /** Deletes a plan without live documents; its source can be used as a whole again. */
  async remove(workspaceId: string, userId: string, planId: string): Promise<void> {
    await this.inTransaction(async (manager) => {
      const plan = await this.lockPlan(manager, workspaceId, planId);
      const documents = await planDocuments(manager, plan.id);
      const live = documents.filter((row) => isLive(row.status));

      if (live.length > 0) {
        throw new ConflictException(
          `Termin documents ${live
            .map((row) => row.number)
            .join(', ')} are still live. Cancel, void or delete them before deleting the plan.`,
        );
      }

      await this.recordPlanEvent(manager, workspaceId, userId, plan, 'deleted', {
        ...(await this.eventTarget(manager, plan)),
        percentages: (await planItems(manager, plan.id)).map((item) => item.percentage.toNumber()),
      });
      await manager.getRepository(TerminPlan).delete({ id: plan.id });
    });
  }

  // ------------------------------------------------------------------ internals

  private requireValidSplit(percentages: number[]): void {
    const error = validatePercentages(percentages);
    if (error) {
      throw new BadRequestException(error);
    }
  }

  private inTransaction<T>(work: (manager: EntityManager) => Promise<T>): Promise<T> {
    return this.plans.manager.transaction(work);
  }

  private async lockPlan(
    manager: EntityManager,
    workspaceId: string,
    planId: string,
  ): Promise<TerminPlan> {
    // Row lock: two "Generate" clicks must not generate the same termin twice.
    const plan = await manager.getRepository(TerminPlan).findOne({
      where: { id: planId, workspaceId },
      lock: { mode: 'pessimistic_write' },
    });
    if (!plan) {
      throw new NotFoundException('Termin plan not found.');
    }
    return plan;
  }

  private async savePlan(
    manager: EntityManager,
    values: Pick<
      TerminPlan,
      'workspaceId' | 'companyId' | 'documentType' | 'sourceDocumentId' | 'basePayload'
    > & { createdById: string; percentages: number[] },
  ): Promise<TerminPlan> {
    const { percentages, ...columns } = values;
    const repository = manager.getRepository(TerminPlan);
    const plan = await repository.save(repository.create({ id: randomUUID(), ...columns }));
    await this.saveItems(manager, plan.id, percentages);
    return plan;
  }

  private async saveItems(
    manager: EntityManager,
    planId: string,
    percentages: number[],
  ): Promise<void> {
    const repository = manager.getRepository(TerminPlanItem);
    await repository.save(
      percentages.map((percentage, index) =>
        repository.create({
          id: randomUUID(),
          planId,
          sequence: index + 1,
          percentage: new Decimal(percentage),
        }),
      ),
    );
  }

  private async generateIn(
    manager: EntityManager,
    workspaceId: string,
    userId: string,
    plan: TerminPlan,
    percentages: number[],
    option: TerminGenerateOption,
    company?: Company,
  ): Promise<TerminPlanResult> {
    const items = await planItems(manager, plan.id);
    const withShare = percentages
      .map((percentage, index) => ({ percentage, sequence: index + 1 }))
      .filter((termin) => termin.percentage > 0)
      .map((termin) => termin.sequence);
    const sequences = option === 'ALL' ? withShare : withShare.slice(0, 1);

    return this.generateSequences(manager, workspaceId, userId, plan, items, sequences, company);
  }

  /** Generates the termins' documents (the plan row is locked by the caller). */
  private async generateSequences(
    manager: EntityManager,
    workspaceId: string,
    userId: string,
    plan: TerminPlan,
    items: TerminPlanItem[],
    sequences: number[],
    company?: Company,
  ): Promise<TerminPlanResult> {
    const percentages = items.map((item) => item.percentage.toNumber());
    const documents = await planDocuments(manager, plan.id);
    const live = new Map(
      documents.filter((row) => isLive(row.status)).map((row) => [Number(row.sequence), row]),
    );
    const assignments: TerminAssignment[] = sequences.map((sequence) => {
      const percentage = percentages[sequence - 1] ?? 0;
      const existing = live.get(sequence);
      if (existing) {
        throw new ConflictException(
          `Termin ${sequence} already has ${existing.number}. Cancel, void or delete it to generate the termin again.`,
        );
      }
      if (percentage <= 0) {
        throw new ConflictException(
          `Termin ${sequence} is 0%. Give it a percentage before generating it.`,
        );
      }
      return {
        planId: plan.id,
        sequence,
        count: items.length,
        percentage,
        bounds: terminBounds(percentages, sequence),
      };
    });

    const generated: TerminPlanResult['documents'] = [];

    if (plan.documentType === DocumentType.GOODS_RECEIPT) {
      const quotation = await this.receipts.lockAcceptedQuotation(
        manager,
        workspaceId,
        plan.sourceDocumentId ?? '',
      );
      for (const termin of assignments) {
        const id = await this.receipts.createReceipt(
          manager,
          workspaceId,
          userId,
          quotation,
          termin,
        );
        generated.push({ id, sequence: termin.sequence });
      }
    } else if (plan.sourceDocumentId) {
      const receipt = await this.conversions.lockReceivedReceipt(
        manager,
        workspaceId,
        plan.sourceDocumentId,
      );
      for (const termin of assignments) {
        const id = await this.conversions.createFromReceipt(
          manager,
          workspaceId,
          userId,
          receipt,
          termin,
        );
        generated.push({ id, sequence: termin.sequence });
      }
    } else {
      const base = plan.basePayload as unknown as InvoicePlanBase;
      const owner = company ?? (await this.requireCompany(plan.companyId));
      for (const termin of assignments) {
        const payload = terminInvoicePayload(base.invoice, termin.bounds);
        if (payload.items.length === 0) {
          throw new ConflictException(
            `Termin ${termin.sequence} (${formatPercentage(termin.percentage)}) is too small: every quantity rounds to zero.`,
          );
        }
        const { id, customerId } = await this.invoices.insertInvoice(
          manager,
          workspaceId,
          userId,
          owner,
          payload,
          termin,
        );
        // A customer typed once is saved with the first termin; later termins bill the same one.
        if (!base.invoice.customer.id) {
          base.invoice.customer.id = customerId;
          await manager.getRepository(TerminPlan).update({ id: plan.id }, {
            basePayload: base as unknown as Record<string, unknown>,
          } as QueryDeepPartialEntity<TerminPlan>);
        }
        generated.push({ id, sequence: termin.sequence });
      }
    }

    return { plan: await loadTerminPlanView(manager, plan), documents: generated };
  }

  private async requireCompany(companyId: string): Promise<Company> {
    const company = await this.companies.findById(companyId);
    if (!company) {
      throw new NotFoundException('The company for this termin plan no longer exists.');
    }
    return company;
  }

  /** Plan events are recorded on the source (or the typed invoice's first live termin). */
  private async eventTarget(
    manager: EntityManager,
    plan: TerminPlan,
  ): Promise<{ targetType: string; targetId: string; number: string | null }> {
    if (plan.sourceDocumentId) {
      const source = await manager
        .getRepository(Document)
        .findOne({ where: { id: plan.sourceDocumentId } });
      return {
        targetType:
          plan.documentType === DocumentType.GOODS_RECEIPT ? 'quotation' : 'goods_receipt',
        targetId: plan.sourceDocumentId,
        number: source?.documentNumber ?? null,
      };
    }
    const documents = await planDocuments(manager, plan.id);
    const first = documents.slice().sort((a, b) => Number(a.sequence) - Number(b.sequence))[0];
    return { targetType: 'invoice', targetId: first?.id ?? plan.id, number: first?.number ?? null };
  }

  private async recordPlanEvent(
    manager: EntityManager,
    workspaceId: string,
    userId: string,
    plan: TerminPlan,
    kind: 'created' | 'updated' | 'deleted',
    event: { targetType: string; targetId: string; number: string | null; percentages: number[] },
  ): Promise<void> {
    const audit = manager.getRepository(AuditEvent);
    await audit.save(
      audit.create({
        workspaceId,
        actorId: userId,
        action: `${event.targetType}.termin_plan_${kind}`,
        targetType: event.targetType,
        targetId: event.targetId,
        metadata: {
          number: event.number,
          planId: plan.id,
          documentType: plan.documentType,
          count: event.percentages.length,
          percentages: event.percentages,
        },
        ip: null,
      }),
    );
  }
}
